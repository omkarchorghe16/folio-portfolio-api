-- A user's own asset types (code CUSTOM_...) and renamed default types (code of the default, e.g. STOCKS).
-- Default types that were never renamed have no row. Codes never change, so a rename applies to every month.
CREATE TABLE portfolio_asset_types_usa (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  country VARCHAR(10) NOT NULL DEFAULT 'US',
  code VARCHAR(40) NOT NULL,
  name VARCHAR(60) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_portfolio_asset_types_usa UNIQUE (user_id, code),
  CONSTRAINT ck_portfolio_asset_types_usa_country CHECK (country = 'US')
);

CREATE TABLE portfolio_asset_types_india (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  country VARCHAR(10) NOT NULL DEFAULT 'India',
  code VARCHAR(40) NOT NULL,
  name VARCHAR(60) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_portfolio_asset_types_india UNIQUE (user_id, code),
  CONSTRAINT ck_portfolio_asset_types_india_country CHECK (country = 'India')
);

-- Entries may now use a user's own types; the service checks the code.
ALTER TABLE portfolio_entries_usa DROP CONSTRAINT ck_portfolio_entries_usa_asset_type;
ALTER TABLE portfolio_entries_india DROP CONSTRAINT ck_portfolio_entries_india_asset_type;
