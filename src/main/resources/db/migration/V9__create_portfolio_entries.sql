-- One row per user, month and asset type, entered by hand. entry_month is always the 1st of the month.
-- invested_amount is the total cost still held in that month. Profit and percentages are calculated, not stored.
CREATE TABLE portfolio_entries_usa (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  country VARCHAR(10) NOT NULL DEFAULT 'US',
  currency VARCHAR(3) NOT NULL DEFAULT 'USD',
  entry_month DATE NOT NULL,
  asset_type VARCHAR(40) NOT NULL,
  invested_amount NUMERIC(20,2) NOT NULL,
  current_value NUMERIC(20,2) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_portfolio_entries_usa UNIQUE (user_id, entry_month, asset_type),
  CONSTRAINT ck_portfolio_entries_usa_country CHECK (country = 'US'),
  CONSTRAINT ck_portfolio_entries_usa_currency CHECK (currency = 'USD'),
  CONSTRAINT ck_portfolio_entries_usa_month CHECK (EXTRACT(DAY FROM entry_month) = 1),
  CONSTRAINT ck_portfolio_entries_usa_amounts CHECK (invested_amount >= 0 AND current_value >= 0),
  CONSTRAINT ck_portfolio_entries_usa_asset_type CHECK (asset_type IN (
    'STOCKS', 'MUTUAL_FUNDS', 'ETFS', 'RESIDENTIAL_PROPERTY', 'COMMERCIAL_PROPERTY', 'LAND',
    'REITS', 'BONDS_FIXED_INCOME', 'CASH', 'CRYPTO', 'GOLD_COMMODITIES'))
);

