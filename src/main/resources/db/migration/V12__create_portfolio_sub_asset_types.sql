-- One asset type has many sub asset types (for example Residential property -> Home, Rental flat).
-- The foreign keys include user_id, so a sub asset type always belongs to the same user as its asset type.
ALTER TABLE portfolio_asset_types_usa ADD CONSTRAINT uq_portfolio_asset_types_usa_owner UNIQUE (user_id, id);
ALTER TABLE portfolio_asset_types_india ADD CONSTRAINT uq_portfolio_asset_types_india_owner UNIQUE (user_id, id);

CREATE TABLE portfolio_sub_asset_types_usa (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  country VARCHAR(10) NOT NULL DEFAULT 'US',
  asset_type_id BIGINT NOT NULL,
  code VARCHAR(40) NOT NULL,
  name VARCHAR(60) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_portfolio_sub_asset_types_usa UNIQUE (user_id, code),
  CONSTRAINT uq_portfolio_sub_asset_types_usa_owner UNIQUE (user_id, id),
  CONSTRAINT ck_portfolio_sub_asset_types_usa_country CHECK (country = 'US'),
  CONSTRAINT fk_portfolio_sub_asset_types_usa_asset_type FOREIGN KEY (user_id, asset_type_id)
    REFERENCES portfolio_asset_types_usa (user_id, id)
);

CREATE TABLE portfolio_sub_asset_types_india (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  country VARCHAR(10) NOT NULL DEFAULT 'India',
  asset_type_id BIGINT NOT NULL,
  code VARCHAR(40) NOT NULL,
  name VARCHAR(60) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_portfolio_sub_asset_types_india UNIQUE (user_id, code),
  CONSTRAINT uq_portfolio_sub_asset_types_india_owner UNIQUE (user_id, id),
  CONSTRAINT ck_portfolio_sub_asset_types_india_country CHECK (country = 'India'),
  CONSTRAINT fk_portfolio_sub_asset_types_india_asset_type FOREIGN KEY (user_id, asset_type_id)
    REFERENCES portfolio_asset_types_india (user_id, id)
);

CREATE INDEX idx_portfolio_sub_asset_types_usa_asset_type ON portfolio_sub_asset_types_usa(user_id, asset_type_id);
CREATE INDEX idx_portfolio_sub_asset_types_india_asset_type ON portfolio_sub_asset_types_india(user_id, asset_type_id);

-- An entry belongs to the asset type itself (NULL) or to one of its sub asset types. Existing entries stay NULL.
ALTER TABLE portfolio_entries_usa ADD COLUMN sub_asset_type_id BIGINT;
ALTER TABLE portfolio_entries_usa ADD CONSTRAINT fk_portfolio_entries_usa_sub_asset_type
  FOREIGN KEY (user_id, sub_asset_type_id) REFERENCES portfolio_sub_asset_types_usa (user_id, id);
ALTER TABLE portfolio_entries_usa DROP CONSTRAINT uq_portfolio_entries_usa;
ALTER TABLE portfolio_entries_usa ADD CONSTRAINT uq_portfolio_entries_usa
  UNIQUE NULLS NOT DISTINCT (user_id, entry_month, asset_type, sub_asset_type_id);

ALTER TABLE portfolio_entries_india ADD COLUMN sub_asset_type_id BIGINT;
ALTER TABLE portfolio_entries_india ADD CONSTRAINT fk_portfolio_entries_india_sub_asset_type
  FOREIGN KEY (user_id, sub_asset_type_id) REFERENCES portfolio_sub_asset_types_india (user_id, id);
ALTER TABLE portfolio_entries_india DROP CONSTRAINT uq_portfolio_entries_india;
ALTER TABLE portfolio_entries_india ADD CONSTRAINT uq_portfolio_entries_india
  UNIQUE NULLS NOT DISTINCT (user_id, entry_month, asset_type, sub_asset_type_id);
