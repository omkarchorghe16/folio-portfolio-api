-- Stocks and ETFs a user holds. Prices stay in folio-market-feed-svc (fmp_stock_profiles, upstox_stock_quotes),
-- so value and profit are calculated from those prices and not stored here.
CREATE TABLE stock_holdings_usa (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  country VARCHAR(10) NOT NULL DEFAULT 'US',
  currency VARCHAR(3) NOT NULL DEFAULT 'USD',
  symbol VARCHAR(20) NOT NULL,
  name VARCHAR(160) NOT NULL,
  asset_type VARCHAR(10) NOT NULL,
  quantity NUMERIC(24,8) NOT NULL,
  average_cost NUMERIC(20,6) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_stock_holdings_usa UNIQUE (user_id, symbol),
  CONSTRAINT ck_stock_holdings_usa_country CHECK (country = 'US'),
  CONSTRAINT ck_stock_holdings_usa_currency CHECK (currency = 'USD'),
  CONSTRAINT ck_stock_holdings_usa_asset_type CHECK (asset_type IN ('STOCK', 'ETF')),
  CONSTRAINT ck_stock_holdings_usa_amounts CHECK (quantity > 0 AND average_cost >= 0)
);

CREATE TABLE stock_holdings_india (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  country VARCHAR(10) NOT NULL DEFAULT 'India',
  currency VARCHAR(3) NOT NULL DEFAULT 'INR',
  symbol VARCHAR(20) NOT NULL,
  exchange VARCHAR(10) NOT NULL DEFAULT 'NSE',
  name VARCHAR(160) NOT NULL,
  asset_type VARCHAR(10) NOT NULL,
  quantity NUMERIC(24,8) NOT NULL,
  average_cost NUMERIC(20,6) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_stock_holdings_india UNIQUE (user_id, symbol, exchange),
  CONSTRAINT ck_stock_holdings_india_country CHECK (country = 'India'),
  CONSTRAINT ck_stock_holdings_india_currency CHECK (currency = 'INR'),
  CONSTRAINT ck_stock_holdings_india_exchange CHECK (exchange IN ('NSE', 'BSE')),
  CONSTRAINT ck_stock_holdings_india_asset_type CHECK (asset_type IN ('STOCK', 'ETF')),
  CONSTRAINT ck_stock_holdings_india_amounts CHECK (quantity > 0 AND average_cost >= 0)
);
